"""The wire protocol must derive from the contract, and must not drift at 64x4.

`tests/data/verified-64x32-request-golden.hex` was generated by the *pre-change*
`protocol.py` from the real contract rows of run `mlp_64_32/20260928-hosta`. Re-encoding
those rows after the change has to reproduce it byte for byte; that is the equivalence
oracle. The synthetic ap_fixed<20,6> cases then prove the framing actually moved.
"""

from __future__ import annotations

import hashlib
import importlib.util
import json
import sys
from pathlib import Path

from geometry_fixtures import synthetic_geometry, wrapper_record

import pytest


SKILL = Path(__file__).resolve().parents[1]
SCRIPTS = SKILL / "scripts"
DATA = SKILL / "tests" / "data"
GOLDEN_REQUEST_SHA256 = "d4af03f90c6159fba7fdbce42fbc5e60142ad4582875b130f14a1e779a2e68db"


def load(name: str):
    spec = importlib.util.spec_from_file_location(name, SCRIPTS / f"{name}.py")
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module


def geometry(precision="ap_fixed<32,12>", elements=64, width=4):
    sys.path.insert(0, str(SCRIPTS))
    module = load("host_geometry")
    return synthetic_geometry(module, 
        {"precision": precision, "model": {"input_shape": [256, elements]}},
        references=[[0.0] * width])


def golden_rows():
    return json.loads((DATA / "verified-64x32-inputs.json").read_text(encoding="utf-8"))


def test_verified_geometry_request_bytes_are_byte_identical_to_the_pre_change_encoder():
    protocol, rows = load("protocol"), golden_rows()
    frames = b"".join(protocol.encode_request(row, index, geometry())
                      for index, row in enumerate(rows))
    assert hashlib.sha256(frames).hexdigest() == GOLDEN_REQUEST_SHA256
    golden = bytes.fromhex((DATA / "verified-64x32-request-golden.hex").read_text().strip())
    assert frames == golden


def test_verified_geometry_response_decoding_is_unchanged():
    protocol = load("protocol")
    frame = bytes.fromhex((DATA / "verified-64x32-response-golden.hex").read_text().strip())
    expected = json.loads((DATA / "verified-64x32-response-golden.json").read_text())
    cycles, values = protocol.decode_response(frame, expected["sequence"], geometry())
    assert cycles == expected["cycles"]
    assert values == expected["values"]


def test_request_frame_length_follows_the_derived_geometry():
    protocol = load("protocol")
    assert len(protocol.encode_request([0.0] * 64, 0, geometry())) == 264
    synthetic = geometry("ap_fixed<20,6>")
    frame = protocol.encode_request([0.0] * 64, 0, synthetic)
    assert len(frame) == 168
    assert frame[:2] == b"\xa5\x5a"
    assert int.from_bytes(frame[4:6], "little") == 160


def test_synthetic_geometry_packs_elements_bit_contiguously():
    """Element i must sit at bits [i*20 +: 20]; the independent packing below is the oracle."""
    protocol = load("protocol")
    module = load("host_geometry")
    synthetic = geometry("ap_fixed<20,6>")
    values = [((index * 37) % 61 - 30) / 8.0 for index in range(64)]
    frame = protocol.encode_request(values, 9, synthetic)
    packed = 0
    for index, value in enumerate(values):
        raw = module.quantise(value, 20, 6) & ((1 << 20) - 1)
        packed |= raw << (20 * index)
    assert frame[6:-2] == packed.to_bytes(160, "little")
    assert int.from_bytes(frame[2:4], "little") == 9


def test_synthetic_geometry_response_unpacks_every_element():
    protocol, module = load("protocol"), load("host_geometry")
    geometry_20 = geometry("ap_fixed<20,6>")
    raws = [1, -1, 16384, -16384]
    packed = 0
    for index, raw in enumerate(raws):
        packed |= (raw & ((1 << 20) - 1)) << (20 * index)
    payload = packed.to_bytes(10, "little")
    body = (b"\x5a\xa5" + (7).to_bytes(2, "little")
            + (14).to_bytes(2, "little") + (1234).to_bytes(4, "little") + payload)
    frame = body + protocol.crc16(body).to_bytes(2, "little")
    cycles, values = protocol.decode_response(frame, 7, geometry_20)
    assert cycles == 1234
    assert values == [raw / float(1 << 14) for raw in raws]
    assert len(frame) == geometry_20.response_frame_bytes == 22


def test_wrong_value_count_sequence_and_range_are_refused():
    protocol = load("protocol")
    with pytest.raises(ValueError, match="64"):
        protocol.encode_request([0.0] * 63, 0, geometry())
    with pytest.raises(ValueError, match="sequence"):
        protocol.encode_request([0.0] * 64, 70000, geometry())
    with pytest.raises(ValueError, match="range"):
        protocol.encode_request([2048.0] * 64, 0, geometry())
    with pytest.raises(ValueError, match="range"):
        protocol.encode_request([-2048.0001] * 64, 0, geometry())


def test_partial_extra_and_stale_responses_are_refused():
    protocol = load("protocol")
    geometry_20 = geometry("ap_fixed<20,6>")
    good = protocol.encode_request([0.0] * 64, 3, geometry_20)
    assert len(good) == 168
    body = b"\x5a\xa5" + (3).to_bytes(2, "little") + (14).to_bytes(2, "little") \
        + (99).to_bytes(4, "little") + bytes(10)
    frame = body + protocol.crc16(body).to_bytes(2, "little")
    with pytest.raises(ValueError, match="length"):
        protocol.decode_response(frame + b"\x00", 3, geometry_20)
    with pytest.raises(ValueError, match="length"):
        protocol.decode_response(frame[:-1], 3, geometry_20)
    with pytest.raises(ValueError, match="sequence"):
        protocol.decode_response(frame, 4, geometry_20)
    broken = frame[:-1] + bytes([frame[-1] ^ 0xFF])
    with pytest.raises(ValueError, match="CRC"):
        protocol.decode_response(broken, 3, geometry_20)
    zero_cycles = (b"\x5a\xa5" + (3).to_bytes(2, "little") + (14).to_bytes(2, "little")
                   + bytes(4) + bytes(10))
    zero_cycles += protocol.crc16(zero_cycles).to_bytes(2, "little")
    with pytest.raises(ValueError, match="cycles"):
        protocol.decode_response(zero_cycles, 3, geometry_20)


